/**
 * 既有数据导出：把设备台账与维护记录导出为 CSV 并分享。
 * 数据经 `gearflow-api` 按当前 OPENID 获取，CSV 在本机生成后通过微信分享给用户，
 * 不经过任何第三方服务器。
 */
import { buildCsvWithBom, type CsvColumn } from '@/utils/csv'
import { centsToYuan } from '@/utils/money'
import { DEVICE_STATUS_LABELS } from '@/constants/device'
import { MAINTENANCE_TYPE_LABELS } from '@/constants/maintenance'
import type { DeviceDoc } from '@/types/device'
import type { MaintenanceDoc } from '@/types/maintenance'
import { AppError, isRecord } from '@/utils/error'
import { assertClientRevision, clientRevision } from './client-state'

let exportSequence = 0

function timestampSuffix(): string {
  const d = new Date()
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}_${pad(d.getHours())}${pad(d.getMinutes())}${pad(d.getSeconds())}_${d.getMilliseconds()}_${++exportSequence}`
}

function deviceColumns(categoryNameOf: (id: string | null) => string): Array<CsvColumn<DeviceDoc>> {
  return [
    { header: '名称', value: (d) => d.name },
    { header: '分类', value: (d) => categoryNameOf(d.categoryId) },
    {
      header: '状态',
      value: (d) => DEVICE_STATUS_LABELS[d.status] ?? d.status,
    },
    { header: '品牌', value: (d) => d.brand },
    { header: '型号', value: (d) => d.model },
    { header: '序列号', value: (d) => d.serialNumber },
    { header: '购买日期', value: (d) => d.purchaseDate },
    { header: '购买渠道', value: (d) => d.purchaseChannel },
    { header: '购买价格(元)', value: (d) => centsToYuan(d.purchasePriceCents) },
    { header: '币种', value: (d) => d.currency },
    { header: '备注', value: (d) => d.notes },
    { header: '录入时间', value: (d) => d.createdAt },
  ]
}

export function buildDevicesCsv(
  devices: DeviceDoc[],
  categoryNameOf: (id: string | null) => string,
): string {
  return buildCsvWithBom(deviceColumns(categoryNameOf), devices)
}

export function buildMaintenanceCsv(
  device: DeviceDoc,
  records: MaintenanceDoc[],
  categoryNameOf: (id: string | null) => string,
): string {
  const columns: Array<CsvColumn<MaintenanceDoc>> = [
    { header: '设备名称', value: () => device.name },
    { header: '设备分类', value: () => categoryNameOf(device.categoryId) },
    { header: '标题', value: (m) => m.title },
    { header: '类型', value: (m) => MAINTENANCE_TYPE_LABELS[m.type] ?? m.type },
    { header: '发生日期', value: (m) => m.occurredAt },
    { header: '费用(元)', value: (m) => centsToYuan(m.costCents) },
    { header: '服务商', value: (m) => m.vendor },
    { header: '备注', value: (m) => m.notes },
    { header: '录入时间', value: (m) => m.createdAt },
  ]
  return buildCsvWithBom(columns, records)
}

/** 微信文件系统/分享的窄接口（第三方类型边界收敛） */
interface WxFileSystemManager {
  writeFileSync(filePath: string, data: string, encoding: string): void
  readdirSync(dirPath: string): string[]
  mkdirSync(dirPath: string, recursive: boolean): void
  unlinkSync(filePath: string): void
}
interface WxShareApi {
  env: { USER_DATA_PATH: string }
  shareFileMessage(options: {
    filePath: string
    success: () => void
    fail: (err: { errMsg?: string }) => void
  }): void
}

function getWxShareApi(): WxShareApi {
  const api = (globalThis as unknown as { wx?: WxShareApi }).wx
  if (!api || typeof api.shareFileMessage !== 'function') {
    throw new AppError('INTERNAL_ERROR', '当前微信版本不支持文件分享，请升级微信')
  }
  return api
}

function fileSystem(): WxFileSystemManager {
  return (uni as unknown as { getFileSystemManager(): WxFileSystemManager }).getFileSystemManager()
}

function fileSystemErrorMessage(error: unknown): string {
  if (!isRecord(error)) return ''
  return [error.errMsg, error.message, error.code]
    .filter((value): value is string => typeof value === 'string')
    .join(' ')
}

function isMissingFile(error: unknown): boolean {
  return /no such file|not exist|\bENOENT\b/i.test(fileSystemErrorMessage(error))
}

function ensureExportDirectory(fs: WxFileSystemManager, directory: string): void {
  try {
    fs.mkdirSync(directory, true)
  } catch (error) {
    if (!/file already exists|\bEEXIST\b/i.test(fileSystemErrorMessage(error))) throw error
  }
}

function removeExport(fs: WxFileSystemManager, path: string): void {
  try {
    fs.unlinkSync(path)
  } catch (error) {
    if (!isMissingFile(error)) {
      throw new AppError('INTERNAL_ERROR', '本机导出文件清理失败，请重试')
    }
  }
}

const EXPORT_DIRECTORY = 'gearflow-exports'
const EXPORT_FILE = /^gearflow_[^/\\\x00-\x1f]+\.csv$/i

/** Only remove files generated by GearFlow, including the old root-level exports. */
export function clearGeneratedExports(): void {
  const api = (globalThis as unknown as { wx?: WxShareApi }).wx
  if (!api) return
  const fs = fileSystem()
  let failure: AppError | null = null
  for (const directory of [
    api.env.USER_DATA_PATH,
    `${api.env.USER_DATA_PATH}/${EXPORT_DIRECTORY}`,
  ]) {
    let names: string[]
    try {
      names = fs.readdirSync(directory)
    } catch (error) {
      if (!isMissingFile(error)) {
        failure ??= new AppError('INTERNAL_ERROR', '无法检查本机导出文件，请重试')
      }
      continue
    }
    for (const name of names) {
      if (!EXPORT_FILE.test(name)) continue
      try {
        removeExport(fs, `${directory}/${name}`)
      } catch {
        failure ??= new AppError('INTERNAL_ERROR', '本机导出文件清理失败，请重试')
      }
    }
  }
  if (failure) throw failure
}

/**
 * 保存 CSV 到本机并唤起微信分享（发送给朋友 / 文件传输助手）。
 * 仅微信小程序端可用。
 */
export async function saveAndShareCsv(
  fileName: string,
  content: string,
  revision = clientRevision(),
): Promise<void> {
  // #ifdef MP-WEIXIN
  const wxApi = getWxShareApi()
  assertClientRevision(revision)
  if (!EXPORT_FILE.test(fileName)) throw new AppError('VALIDATION_ERROR', '导出文件名无效')
  const fs = fileSystem()
  const directory = `${wxApi.env.USER_DATA_PATH}/${EXPORT_DIRECTORY}`
  const filePath = `${directory}/${fileName}`
  try {
    try {
      ensureExportDirectory(fs, directory)
      fs.writeFileSync(filePath, content, 'utf8')
    } catch {
      throw new AppError('INTERNAL_ERROR', '导出文件生成失败，请检查存储空间')
    }
    await new Promise<void>((resolve, reject) => {
      wxApi.shareFileMessage({
        filePath,
        success: () => resolve(),
        fail: (err) => {
          // Cancellation still runs the same temporary-file cleanup.
          if (err.errMsg && err.errMsg.includes('cancel')) {
            resolve()
            return
          }
          reject(new AppError('INTERNAL_ERROR', '分享失败，请重试'))
        },
      })
    })
  } finally {
    removeExport(fs, filePath)
  }
  return
  // #endif

  // #ifndef MP-WEIXIN
  throw new Error('当前平台暂不支持文件导出，请在微信小程序内使用')
  // #endif
}

/** 组装导出文件名：前缀_时间戳.csv */
export function csvFileName(prefix: string): string {
  const safePrefix = prefix.replace(/[/\\:<>"|?*\x00-\x1f]/g, '_').slice(0, 100)
  return `${safePrefix}_${timestampSuffix()}.csv`
}
